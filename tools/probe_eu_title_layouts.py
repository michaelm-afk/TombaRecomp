#!/usr/bin/env python3
"""Find original EU event-title layouts; emit offsets only, never game data."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'tools'), str(ROOT / 'psxrecomp/tools')]
import extract_overlays as iso
from probe_eu_languages import US_SHA1, EU_SHA1


def word(data, offset):
    return struct.unpack_from('<I', data, offset)[0]


def find_tables(data):
    """200 event pointers followed by their own table-address global.

    Infer each file's actual load base from that backlink, then validate every
    pointed-to positioning record. No upstream EU addresses are assumed.
    """
    result = []
    for start in range(0, len(data) - 803, 4):
        base = word(data, start + 800) - start
        if not 0x80010000 <= base < 0x80200000:
            continue
        lists = []
        for event in range(200):
            offset = word(data, start + event * 4) - base
            if not 0 <= offset < len(data) - 3:
                break
            end = offset
            while end + 4 <= len(data) and end - offset < 96 * 4:
                marker, x, y, style = struct.unpack_from('<BbbB', data, end)
                if marker == 255:
                    break
                if marker != 0 or abs(x) > 40 or abs(y) > 12:
                    break
                end += 4
            if end + 4 > len(data) or data[end] != 255:
                break
            lists.append((offset, (end - offset) // 4))
        if len(lists) == 200:
            result.append((start, base, lists))
    return result


def probe(us_path, eu_path):
    for path, expected in [(us_path, US_SHA1), (eu_path, EU_SHA1)]:
        with path.open('rb') as stream:
            if hashlib.file_digest(stream, 'sha1').hexdigest() != expected:
                raise ValueError(f'Unsupported disc: {path}')
    us = iso.DiscReader(str(us_path), raw=True)
    eu = iso.DiscReader(str(eu_path), raw=True)
    rows = []
    try:
        eu_files = {n: (l, s) for n, l, s in iso.enumerate_files(eu)}
        seen = {}
        for name, lba, size in iso.enumerate_files(us):
            if not name.endswith('.BIN') or name.startswith('SYS/'):
                continue
            data = us.read_file_bytes(lba, size)
            tables = find_tables(data)
            for table, base, lists in tables:
                key = base + table
                targets = []
                for language in range(5):
                    folder, filename = name.rsplit('/', 1)
                    donor_name = folder + '/' + filename[0] + str(language) + filename[1:]
                    donor_lba, donor_size = eu_files[donor_name]
                    donor = eu.read_file_bytes(donor_lba, donor_size)
                    donor_tables = find_tables(donor)
                    if len(tables) != 1 or len(donor_tables) != 1:
                        raise ValueError(f'Ambiguous title table: {donor_name}')
                    dt, db, dl = donor_tables[0]
                    first = min(off for off, count in dl)
                    last = max(dt + 800, max(off + count * 4 + 4 for off, count in dl))
                    if last > dt + 800 or first >= dt:
                        raise ValueError(f'Layout data overlaps unrelated region: {donor_name}')
                    targets.append(dict(path=donor_name, offset=donor_lba * 2048 + first,
                                        size=last - first, original_begin=db + first,
                                        table_offset=dt - first,
                                        layout_sha256=hashlib.sha256(donor[first:last]).hexdigest(),
                                        counts=[count for off, count in dl],
                                        rows=[[sum(donor[off + j * 4 + 2] == y for j in range(count))
                                               for y in sorted({donor[off + j * 4 + 2] for j in range(count)},
                                                               key=lambda y: y if y < 128 else y - 256)]
                                              for off, count in dl]))
                entry = dict(source=name, us_table=key, targets=targets)
                # SYSTEM mirrors and area copies must agree before deduplicating.
                fingerprint = [(t['original_begin'], t['table_offset'], t['layout_sha256']) for t in targets]
                if key in seen:
                    if seen[key] != fingerprint:
                        raise ValueError(f'Conflicting US table address: {name}')
                    continue
                seen[key] = fingerprint
                rows.append(entry)
    finally:
        us.close()
        eu.close()
    return rows


def catalog(rows):
    lines = ['/* Offsets only; generated by tools/probe_eu_title_layouts.py. */',
             'static const TitleTable title_tables[] = {']
    for row in rows:
        targets = ', '.join('{%du, %du, 0x%Xu, %du}' %
                            (t['offset'], t['size'], t['original_begin'], t['table_offset'])
                            for t in row['targets'])
        lines.append('    {0x%Xu, {%s}}, /* %s */' % (row['us_table'], targets, row['source']))
    return '\n'.join(lines + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--us-bin', type=Path, required=True)
    parser.add_argument('--eu-bin', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--catalog', type=Path, required=True)
    args = parser.parse_args()
    rows = probe(args.us_bin, args.eu_bin)
    args.report.write_text(json.dumps(rows, indent=2) + '\n', encoding='utf-8')
    args.catalog.write_text(catalog(rows), encoding='utf-8')
    print(f'{len(rows)} original 200-entry title tables mapped across all five languages')
    first = next(r for r in rows if r['source'] == 'AREA00/X00.BIN')
    print('First quest, original EU row lengths:', [t['rows'][1] for t in first['targets']])
    assert first['targets'][2]['rows'][1] == [13, 5], 'German first-quest line regression'


if __name__ == '__main__':
    main()
